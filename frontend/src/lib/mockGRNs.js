export const getGRNById       = (id) => mockGRNs.find((g) => g.id === id) ?? null;
export const getGRNsByWarehouse = (warehouseId) => mockGRNs.filter((g) => g.warehouseId === warehouseId);
export const getGRNsByIPC     = (ipc) => mockGRNs.filter((g) => g.ipc === ipc);
export const getGRNsByCommodity = (commodity) => mockGRNs.filter((g) => g.commodity === commodity);

// ── Summary stats ─────────────────────────────────────────────
export const getGRNStats = () => ({
  total: mockGRNs.length,
  confirmed: mockGRNs.filter((g) => g.status === GRN_STATUS.CONFIRMED).length,
  pending:   mockGRNs.filter((g) => g.status === GRN_STATUS.PENDING).length,
  totalKg:   mockGRNs.reduce((sum, g) => sum + g.quantityKg, 0),
  totalBags: mockGRNs.reduce((sum, g) => sum + g.numberOfBags, 0),
});
